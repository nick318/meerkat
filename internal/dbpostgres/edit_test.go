func originsOf(t *testing.T, conn *PostgresConnection, sql string) []dbclient.ColumnOrigin {
	t.Helper()
	return execOK(t, conn.Execute, sql).Origins
}

func TestTheServerSaysWhereEachColumnCameFrom(t *testing.T) {
	conn := editFixture(t)
	ctx := context.Background()
	target := must(conn.EditTarget(ctx, originsOf(t, conn, "SELECT id FROM meerkat_edit.customers")[0].Table))
	if target == nil || target.Name != "customers" || target.Kind != 'r' {
		t.Fatalf("target = %+v", target)
	}
	editable := func(sql string) dbclient.Editability {
		t.Helper()
		return dbclient.Editable(originsOf(t, conn, sql), target, false, false)
	}

	renamed := editable("SELECT id, name AS customer, lower(email) FROM meerkat_edit.customers")
	if !renamed.OK() || !renamed.Columns[1].Editable || renamed.Columns[2].Locked != "expression" {
		t.Fatalf("renamed: %+v", renamed)
	}
	if got := editable("SELECT * FROM (SELECT id, email FROM meerkat_edit.customers) s"); !got.OK() {
		t.Fatalf("subquery: %v", got.Blocker)
	}
	if got := editable("WITH c AS (SELECT id, email FROM meerkat_edit.customers) SELECT * FROM c"); !got.OK() {
		t.Fatalf("CTE: %v", got.Blocker)
	}
	if got := editable("SELECT c.id, e.what FROM meerkat_edit.customers c CROSS JOIN meerkat_edit.events e"); got.Blocker != dbclient.BlockedTables {
		t.Fatalf("join: %v", got.Blocker)
	}
	if got := editable("SELECT email FROM meerkat_edit.customers"); got.Blocker != dbclient.BlockedKeyMissing {
		t.Fatalf("no key column: %v", got.Blocker)
	}
	if got := editable("SELECT id, slug FROM meerkat_edit.customers"); got.Columns[1].Locked != "generated" {
		t.Fatalf("generated: %+v", got.Columns[1])
	}

	view := originsOf(t, conn, "SELECT * FROM meerkat_edit.pro")
	viewTarget := must(conn.EditTarget(ctx, view[0].Table))
	if got := dbclient.Editable(view, viewTarget, false, false); got.Blocker != dbclient.BlockedView {
		t.Fatalf("view: %v", got.Blocker)
	}
	keyless := originsOf(t, conn, "SELECT * FROM meerkat_edit.events")
	keylessTarget := must(conn.EditTarget(ctx, keyless[0].Table))
	if got := dbclient.Editable(keyless, keylessTarget, false, false); got.Blocker != dbclient.BlockedNoKey {
		t.Fatalf("no key: %v", got.Blocker)
	}
	if got := must(conn.EditTarget(ctx, 1)); got != nil {
		t.Fatalf("oid 1: %+v", got)
	}
}

func TestTheTargetCarriesEnumLabelsAndFlags(t *testing.T) {
	conn := editFixture(t)
	oid := originsOf(t, conn, "SELECT id FROM meerkat_edit.customers")[0].Table
	target := must(conn.EditTarget(context.Background(), oid))
	byName := map[string]dbclient.EditColumn{}
	for _, column := range target.Columns {
		byName[column.Name] = column
	}
	if got := strings.Join(byName["plan"].Labels, ","); got != "free,pro,team" {
		t.Fatalf("labels = %q", got)
	}
	if !byName["active"].Bool || byName["name"].Bool {
		t.Fatal("bool flag wrong")
	}
	if !byName["slug"].Generated || byName["id"].IdentityAlways {
		t.Fatal("generated or identity wrong")
	}
	if len(target.Key) != 1 || target.Columns[target.Key[0]].Name != "id" {
		t.Fatalf("key = %v", target.Key)
	}
}

// editSession opens a session and reads the target the way the shell does.
func editSession(t *testing.T, conn *PostgresConnection) (dbclient.Session, *dbclient.EditTarget, map[string]int16) {
	t.Helper()
	ctx := context.Background()
	session := must(conn.OpenSession(ctx))
	t.Cleanup(func() { session.Close(context.Background()) })
	oid := originsOf(t, conn, "SELECT id FROM meerkat_edit.customers")[0].Table
	target := must(conn.EditTarget(ctx, oid))
	attnum := map[string]int16{}
	for n, column := range target.Columns {
		attnum[column.Name] = n
	}
	return session, target, attnum
}

func TestAnApplyCommitsAndReturnsTheRows(t *testing.T) {
	conn := editFixture(t)
	ctx := context.Background()
	session, target, a := editSession(t, conn)

	outcome, err := session.Apply(ctx, target, []dbclient.RowChange{
		dbclient.RowChangeUpdate{
			Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(1)}},
			Set: []dbclient.AttrValue{{Column: a["email"], Value: text("ANA@lumen.dev")}},
		},
		dbclient.RowChangeInsert{Values: []dbclient.AttrValue{{Column: a["email"], Value: text("dee@kiln.studio")}}},
		dbclient.RowChangeDelete{Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(2)}}},
	}, []int16{a["id"], a["slug"], a["plan"]})
	if err != nil {
		t.Fatal(err)
	}
	if !outcome.Committed {
		t.Fatal("not committed")
	}
	// The generated column came back recomputed.
	wantValue(t, outcome.Rows[0][1], text("ana@lumen.dev"))
	// The insert came back with its id and its default.
	wantValue(t, outcome.Rows[1][0], dbclient.ValueInt(4))
	wantValue(t, outcome.Rows[1][2], text("free"))
	if outcome.Rows[2] != nil {
		t.Fatal("a delete returned a row")
	}
	// Another connection sees it: it committed.
	count := execOK(t, conn.Execute, "SELECT count(*) FROM meerkat_edit.customers")
	wantValue(t, count.Rows[0][0], dbclient.ValueInt(3))
}

func TestAGoneRowRollsEverythingBack(t *testing.T) {
	conn := editFixture(t)
	ctx := context.Background()
	session, target, a := editSession(t, conn)

	_, err := session.Apply(ctx, target, []dbclient.RowChange{
		dbclient.RowChangeUpdate{
			Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(1)}},
			Set: []dbclient.AttrValue{{Column: a["name"], Value: text("first")}},
		},
		// Somebody deleted it since it was read.
		dbclient.RowChangeUpdate{
			Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(99)}},
			Set: []dbclient.AttrValue{{Column: a["name"], Value: text("second")}},
		},
	}, nil)
	var refused *dbclient.ApplyError
	if !errors.As(err, &refused) || !refused.Conflict || refused.Change != 1 {
		t.Fatalf("err = %v", err)
	}
	got := execOK(t, conn.Execute, "SELECT name FROM meerkat_edit.customers WHERE id = 1")
	wantValue(t, got.Rows[0][0], text("Ana"))
	if in := must(session.InTransaction(ctx)); in {
		t.Fatal("left a transaction open")
	}
}

