func TestEveryAwkwardTypeRoundTripsAsText(t *testing.T) {
	conn := editFixture(t)
	ctx := context.Background()
	session, target, a := editSession(t, conn)
	_, err := session.Apply(ctx, target, []dbclient.RowChange{
		dbclient.RowChangeUpdate{
			Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(1)}},
			Set: []dbclient.AttrValue{
				{Column: a["plan"], Value: text("team")},
				{Column: a["tags"], Value: text("{1,2,3}")},
				{Column: a["doc"], Value: text(`{"k": [1, "two"]}`)},
				{Column: a["blob"], Value: text(`\xcafe`)},
				{Column: a["span"], Value: text("1 day 02:00:00")},
				{Column: a["credit"], Value: dbclient.ValueNull{}},
				{Column: a["name"], Value: text("")},
			},
		},
	}, nil)
	if err != nil {
		t.Fatal(err)
	}
	got := execOK(t, conn.Execute,
		"SELECT plan, tags, doc, blob, span, credit IS NULL, name FROM meerkat_edit.customers WHERE id = 1").Rows[0]
	wantValue(t, got[0], text("team"))
	wantValue(t, got[1], text("{1,2,3}"))
	wantValue(t, got[2], text(`{"k": [1, "two"]}`))
	wantValue(t, got[3], dbclient.ValueBytes{0xca, 0xfe})
	wantValue(t, got[4], text("1 day 02:00:00"))
	wantValue(t, got[5], dbclient.ValueBool(true))
	wantValue(t, got[6], text(""))
}

func TestReloadReadsTheRowAgain(t *testing.T) {
	conn := editFixture(t)
	ctx := context.Background()
	session, target, a := editSession(t, conn)
	execOK(t, conn.Execute, "UPDATE meerkat_edit.customers SET name = 'Changed' WHERE id = 2")
	row, err := session.Reload(ctx, target, []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(2)}}, []int16{a["id"], a["name"]})
	if err != nil {
		t.Fatal(err)
	}
	wantValue(t, row[1], text("Changed"))
	gone, err := session.Reload(ctx, target, []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(99)}}, []int16{a["id"]})
	if err != nil || gone != nil {
		t.Fatalf("gone = %v, err = %v", gone, err)
	}
}
