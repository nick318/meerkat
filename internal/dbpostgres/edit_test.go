func TestInsideATransactionTheApplyIsFencedOff(t *testing.T) {
	conn := editFixture(t)
	ctx := context.Background()
	session, target, a := editSession(t, conn)
	if err := session.Begin(ctx); err != nil {
		t.Fatal(err)
	}
	execOK(t, session.Execute, "UPDATE meerkat_edit.customers SET name = 'mine' WHERE id = 3")

	// A refused apply leaves the user's own statement in place.
	_, err := session.Apply(ctx, target, []dbclient.RowChange{
		dbclient.RowChangeUpdate{
			Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(1)}},
			Set: []dbclient.AttrValue{{Column: a["credit"], Value: text("nope")}},
		},
	}, nil)
	if err == nil {
		t.Fatal("not refused")
	}
	outcome, err := session.Apply(ctx, target, []dbclient.RowChange{
		dbclient.RowChangeUpdate{
			Key: []dbclient.AttrValue{{Column: a["id"], Value: dbclient.ValueInt(1)}},
			Set: []dbclient.AttrValue{{Column: a["name"], Value: text("held")}},
		},
	}, nil)
	if err != nil || outcome.Committed {
		t.Fatalf("outcome = %+v, err = %v", outcome, err)
	}
	if in := must(session.InTransaction(ctx)); !in {
		t.Fatal("the transaction is gone")
	}
	// Nobody else sees it yet.
	got := execOK(t, conn.Execute, "SELECT name FROM meerkat_edit.customers WHERE id = 1")
	wantValue(t, got.Rows[0][0], text("Ana"))
	mine := execOK(t, session.Execute, "SELECT name FROM meerkat_edit.customers WHERE id IN (1, 3) ORDER BY id")
	wantValue(t, mine.Rows[0][0], text("held"))
	wantValue(t, mine.Rows[1][0], text("mine"))
}

