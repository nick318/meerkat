func previewTarget() *dbclient.EditTarget {
	return &dbclient.EditTarget{
		OID: 1, Schema: "public", Name: "Customers", Kind: 'r', Key: []int16{1},
		Columns: map[int16]dbclient.EditColumn{
			1: {Name: "id"},
			2: {Name: "email"},
			3: {Name: "note"},
		},
	}
}

func TestAnUpdateNamesTheRowByItsKey(t *testing.T) {
	change := dbclient.RowChangeUpdate{
		Key: []dbclient.AttrValue{{Column: 1, Value: dbclient.ValueInt(1043)}},
		Set: []dbclient.AttrValue{{Column: 2, Value: text("c.li@harbor.app")}, {Column: 3, Value: dbclient.ValueNull{}}},
	}
	st := buildChange(previewTarget(), change, []int16{1, 2}, false)
	want := `UPDATE "public"."Customers" SET "email" = $1, "note" = $2
 WHERE "id" = $3
RETURNING "id", "email"`
	if st.sql != want {
		t.Fatalf("sql:\n%s\nwant:\n%s", st.sql, want)
	}
	if len(st.params) != 3 {
		t.Fatalf("params = %v", st.params)
	}
}

func TestThePreviewWritesTheValuesAsLiterals(t *testing.T) {
	got := previewChanges(previewTarget(), []dbclient.RowChange{
		dbclient.RowChangeInsert{Values: []dbclient.AttrValue{{Column: 2, Value: text("o'neil@x.io")}}},
		dbclient.RowChangeInsert{},
		dbclient.RowChangeDelete{Key: []dbclient.AttrValue{{Column: 1, Value: dbclient.ValueInt(7)}}},
	}, []int16{1})
	want := []string{
		"INSERT INTO \"public\".\"Customers\" (\"email\")\n VALUES ('o''neil@x.io')\nRETURNING \"id\";",
		"INSERT INTO \"public\".\"Customers\" DEFAULT VALUES\nRETURNING \"id\";",
		"DELETE FROM \"public\".\"Customers\"\n WHERE \"id\" = 7;",
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("statement %d:\n%s\nwant:\n%s", i, got[i], want[i])
		}
	}
}

